#ifndef BUTTON_H
#define BUTTON_H

/**
 * @file Button.h
 * @brief Debounced push-button input handler with short press, long press, and repeat modes.
 */

class Button {
public:
    /**
     * @brief Operating mode for handling held-down button events.
     */
    enum class Mode {
        LongPress, ///< Triggers a single LongPressed event once longPressDelay is reached.
        Repeat     ///< Triggers repeated events at periodic intervals while held.
    };

    /**
     * @brief Logical debounced state of the button.
     */
    enum class State {
        Released,  ///< Button is currently released (inactive).
        Pressed    ///< Button is currently pressed (active).
    };

    /**
     * @brief Events generated by the button during update() calls.
     */
    enum Event {
        None,         ///< No event occurred during this update cycle.
        ShortPressed, ///< Button was pressed and released before longPressDelay elapsed.
        LongPressed,  ///< Button was held down for at least longPressDelay in Mode::LongPress.
        Repeat        ///< Button is held down in Mode::Repeat (triggers after initial delay, then at repeat intervals).
    };

    /**
     * @brief Construct a new Button instance.
     * 
     * @param pin Arduino digital pin connected to the button.
     * @param pressedState Logic level representing the pressed state (LOW for active-low / pull-up, HIGH for active-high). Defaults to LOW.
     */
    Button(int pin, int pressedState = LOW);

    /**
     * @brief Default destructor.
     */
    ~Button() = default;

    /**
     * @brief Initialize button configuration, timing thresholds, and initial pin state.
     * 
     * @param now Pointer to the current system timestamp in milliseconds (e.g., &now).
     *            Allows unified time tracking or simulated time acceleration across modules.
     * @param mode Operating mode (Mode::LongPress or Mode::Repeat).
     * @param debounceDelay Minimum duration in ms for raw signal stabilization to filter contact bounce (default: 50 ms).
     * @param longPressDelay Minimum duration in ms the button must be held to trigger a long press or initial repeat (default: 1000 ms).
     * @param repeatInterval Duration in ms between consecutive repeat events when held down in Mode::Repeat (default: 500 ms).
     */
    void begin(unsigned long *now, Mode mode, int debounceDelay = 50, long int longPressDelay = 1000, long int repeatInterval = 500);

    /**
     * @brief Get the current debounced physical state of the button.
     * 
     * @return State Current debounced state (State::Pressed or State::Released).
     */
    State getState();

    /**
     * @brief Update the internal debouncing state machine and detect press events.
     * 
     * This method must be called regularly in the application loop.
     * 
     * @return Event The event detected in this cycle (None, ShortPressed, LongPressed, or Repeat).
     */
    Event update();

private:
    /**
     * @brief Read the hardware pin and map the electrical level to logical button State.
     * 
     * @return State Instantaneous raw state (Pressed or Released).
     */
    State _readPin();

    int _pin;                     ///< Pin associated with this button.
    Mode _mode;                   ///< Button mode (see Button::Mode enum).
    int _pressedState;            ///< Defines whether pressed is LOW or HIGH.
    unsigned long *_pNow;         ///< Pointer to system time in ms (used instead of millis() to allow for time acceleration/simulation).
    unsigned long _debounceDelay;  ///< Minimum duration in ms before confirming a state change.
    unsigned long _longPressDelay; ///< Minimum duration in ms before declaring a long press event.
    unsigned long _repeatInterval; ///< Minimum duration in ms between consecutive repeat events.

    State _state;                 ///< Current debounced button state.
    State _lastRawState;          ///< Last raw button state read from the pin (used for debounce edge detection).
    unsigned long _lastDebounceTime; ///< Last timestamp when raw input changed (ms).
    unsigned long _pressStartTime;   ///< Timestamp when the button was pressed or when last repeat fired (ms).
    bool _longPressFired;         ///< Flag registering whether a long press or initial repeat event has already fired.
};

#endif // BUTTON_H
